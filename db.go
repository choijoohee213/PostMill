//go:embed schema.sql
var schemaSQL string

// 게시물 상태.
const (
	StatusGenerating = "generating"
	StatusPending    = "pending"
	StatusApproved   = "approved"
	StatusPublishing = "publishing"
	StatusPublished  = "published"
	StatusFailed     = "failed"
	StatusHeld       = "held"
)

// 제휴사.
const (
	AffiliateCoupang = "coupang"
	AffiliateToss    = "toss"
)

type Post struct {
	ID               int64
	UserID           string
	Affiliate        string
	ProductURL       string
	AffiliateLink    string
	Memo             string
	ProductName      string
	Body             string
	Detail           string
	Detail2          string
	Status           string
	ErrorMsg         string
	ThreadPermalink  string
	ThreadPostID     string
	RepliesDone      int
	LastReplyID      string
	PublishStartedAt *time.Time
	LinkAuto         bool  // 제휴 링크를 토스 API가 발급했는지
	TacaItemID       int64 // 토스 API로 고른 상품. 0이면 없음
	CreatedAt        time.Time
	PublishedAt      *time.Time
}

type DB struct {
	pool *pgxpool.Pool
}

// Open은 커넥션 풀을 열고 schema.sql을 실행한다.
func Open(ctx context.Context, databaseURL string) (*DB, error) {
	pool, err := pgxpool.New(ctx, databaseURL)
	if err != nil {
		return nil, err
	}
	if _, err := pool.Exec(ctx, schemaSQL); err != nil {
		pool.Close()
		return nil, err
	}
	return &DB{pool: pool}, nil
}

func (db *DB) Close() { db.pool.Close() }

const postColumns = `id, user_id, affiliate, product_url, affiliate_link, memo, product_name, body, detail, detail2,
	status, error_msg, thread_permalink,
	thread_post_id, replies_done, last_reply_id, publish_started_at,
	link_auto, taca_item_id,
	created_at, published_at`

func scanPost(row pgx.Row) (*Post, error) {
	var p Post
	err := row.Scan(&p.ID, &p.UserID, &p.Affiliate, &p.ProductURL, &p.AffiliateLink, &p.Memo,
		&p.ProductName, &p.Body, &p.Detail, &p.Detail2, &p.Status, &p.ErrorMsg, &p.ThreadPermalink,
		&p.ThreadPostID, &p.RepliesDone, &p.LastReplyID, &p.PublishStartedAt,
		&p.LinkAuto, &p.TacaItemID,
		&p.CreatedAt, &p.PublishedAt)
	if err != nil {
		return nil, err
	}
	return &p, nil
}

// CreateDraft는 generating 상태의 row를 만들고 id를 반환한다.
func (db *DB) CreateDraft(ctx context.Context, userID, affiliate, productURL, affiliateLink, memo string) (int64, error) {
	var id int64
	err := db.pool.QueryRow(ctx,
		`INSERT INTO posts (user_id, affiliate, product_url, affiliate_link, memo, status)
		 VALUES ($1, $2, $3, $4, $5, $6) RETURNING id`,
		userID, affiliate, productURL, affiliateLink, memo, StatusGenerating).Scan(&id)
	return id, err
}

// GetPost는 그 사용자의 게시물만 반환한다. 남의 글은 없는 것과 같다.
func (db *DB) GetPost(ctx context.Context, userID string, id int64) (*Post, error) {
	return scanPost(db.pool.QueryRow(ctx,
		`SELECT `+postColumns+` FROM posts WHERE id = $1 AND user_id = $2`, id, userID))
}

// ListByStatus는 주어진 상태들의 게시물을 최신순으로 반환한다.
// query가 있으면 본문·답글·상품명에 그 말이 들어간 글만 고른다.
func (db *DB) ListByStatus(ctx context.Context, userID, query string, statuses ...string) ([]*Post, error) {
	// %와 _는 LIKE에서 특수 문자라 글자 그대로 찾도록 막는다.
	pattern := "%" + strings.NewReplacer(`\`, `\\`, "%", `\%`, "_", `\_`).Replace(query) + "%"
	rows, err := db.pool.Query(ctx,
		`SELECT `+postColumns+` FROM posts
		 WHERE user_id = $1 AND status = ANY($2)
		   AND ($3 = '' OR body ILIKE $4 OR detail ILIKE $4 OR detail2 ILIKE $4 OR product_name ILIKE $4)
		 ORDER BY created_at DESC`,
		userID, statuses, query, pattern)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var posts []*Post
	for rows.Next() {
		p, err := scanPost(rows)
		if err != nil {
			return nil, err
		}
		posts = append(posts, p)
	}
	return posts, rows.Err()
}

// SetGenerated는 초안 생성이 끝난 row를 pending으로 전환한다.
func (db *DB) SetGenerated(ctx context.Context, id int64, body, detail, detail2 string) error {
	_, err := db.pool.Exec(ctx,
		`UPDATE posts SET body = $2, detail = $3, detail2 = $4, status = $5, error_msg = ''
		 WHERE id = $1`,
		id, body, detail, detail2, StatusPending)
	return err
}

// SetAutoGenerated는 AI가 상품까지 고른 초안을 저장한다.
// 링크까지 자동으로 발급했으면 함께 넣고 자동 발급으로 표시한다.
func (db *DB) SetAutoGenerated(ctx context.Context, id int64, d AutoDraft) error {
	_, err := db.pool.Exec(ctx,
		`UPDATE posts SET product_name = $2, product_url = $3, body = $4, detail = $5,
		 detail2 = $6, status = $7, error_msg = '',
		 affiliate_link = CASE WHEN $8 <> '' THEN $8 ELSE affiliate_link END,
		 link_auto = (link_auto OR $8 <> ''), taca_item_id = $9
		 WHERE id = $1`,
		id, d.ProductName, d.ProductURL, d.Body, d.Detail, d.Detail2, StatusPending, d.AffiliateLink, d.TacaItemID)
	return err
}

// UpdateLink는 상세 화면에서 입력한 제휴 링크를 저장한다.
func (db *DB) UpdateLink(ctx context.Context, userID string, id int64, link string) error {
	_, err := db.pool.Exec(ctx,
		`UPDATE posts SET affiliate_link = $3,
		   link_auto = (link_auto AND affiliate_link = $3)
		 WHERE id = $1 AND user_id = $2`, id, userID, link)
	return err
}

// ResetForRegenerate는 카드를 비우고 다시 생성 대기 상태로 되돌린다.
// 자동 발급한 링크는 이전 상품의 것이므로 함께 비운다.
func (db *DB) ResetForRegenerate(ctx context.Context, userID string, id int64) error {
	_, err := db.pool.Exec(ctx,
		`UPDATE posts SET body = '', detail = '', detail2 = '', product_name = '', product_url = '',
		 affiliate_link = CASE WHEN link_auto THEN '' ELSE affiliate_link END, link_auto = false,
		 taca_item_id = 0,
		 status = $3, error_msg = '' WHERE id = $1 AND user_id = $2`,
		id, userID, StatusGenerating)
	return err
}

