// ExpireImages는 붙인 지 오래된 사진을 지운다. 크론이 없으므로 화면을 열 때 부른다.
//
// 게시 중인 글의 사진은 남긴다. Threads가 아직 가져가지 않았을 수 있다.
func (db *DB) ExpireImages(ctx context.Context, olderThan time.Duration) error {
	_, err := db.pool.Exec(ctx,
		`DELETE FROM post_images i USING posts p
		 WHERE i.post_id = p.id AND p.status <> $1
		   AND i.created_at < now() - $2::interval`,
		StatusPublishing, olderThan.String())
	return err
}

// PostsByTacaItems는 토스 상품 ID로 내 글을 찾는다. 같은 상품으로 여러 번 썼으면
// 게시한 글을, 그중에서도 최근 글을 고른다.
func (db *DB) PostsByTacaItems(ctx context.Context, userID string, ids []int64) (map[int64]*Post, error) {
	rows, err := db.pool.Query(ctx,
		`SELECT `+postColumns+` FROM posts
		 WHERE user_id = $1 AND taca_item_id = ANY($2)
		 ORDER BY (status = $3), id`,
		userID, ids, StatusPublished)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	out := map[int64]*Post{}
	for rows.Next() {
		p, err := scanPost(rows)
		if err != nil {
			return nil, err
		}
		// 뒤에 오는 행이 게시한 글, 최근 글이라 덮어쓴다.
		out[p.TacaItemID] = p
	}
	return out, rows.Err()
}

